-- Oracle 19c 전용 이력. 공통 마이그레이션의 동일 버전과 기능을 맞춥니다.
-- 모든 도메인의 소유권은 외래키로 연결합니다. 예약·취향을 공개 게시물 JSON에 섞지 않습니다.
CREATE TABLE members (
 id VARCHAR2(36 CHAR) PRIMARY KEY, email VARCHAR2(254 CHAR) UNIQUE NOT NULL, password_hash VARCHAR2(255 CHAR) NOT NULL,
 nickname VARCHAR2(40 CHAR) NOT NULL, role VARCHAR2(20 CHAR) DEFAULT 'USER' NOT NULL, verified NUMBER(1) DEFAULT 0 NOT NULL CHECK (verified IN (0,1)),
 preferences CLOB DEFAULT '[]' NOT NULL, dm_scope VARCHAR2(20 CHAR) DEFAULT 'ALL' NOT NULL,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);
CREATE TABLE email_tokens (
 token_hash VARCHAR2(64 CHAR) PRIMARY KEY, member_id VARCHAR2(36 CHAR) NOT NULL REFERENCES members(id),
 purpose VARCHAR2(20 CHAR) NOT NULL, expires_at TIMESTAMP NOT NULL
);
CREATE TABLE trips (
 id VARCHAR2(36 CHAR) PRIMARY KEY, owner_id VARCHAR2(36 CHAR) NOT NULL REFERENCES members(id), title VARCHAR2(100 CHAR) NOT NULL,
 regions CLOB NOT NULL, start_date DATE NOT NULL, end_date DATE NOT NULL, origin VARCHAR2(150 CHAR) NOT NULL,
 party_size NUMBER(10) NOT NULL, budget NUMBER(10) NOT NULL, transport VARCHAR2(20 CHAR) NOT NULL,
 preferences CLOB NOT NULL, lodging VARCHAR2(150 CHAR), version NUMBER(10) DEFAULT 0 NOT NULL,
 share_token VARCHAR2(64 CHAR) UNIQUE, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);
CREATE TABLE trip_members (
 trip_id VARCHAR2(36 CHAR) NOT NULL REFERENCES trips(id) ON DELETE CASCADE, member_id VARCHAR2(36 CHAR) NOT NULL REFERENCES members(id),
 PRIMARY KEY(trip_id, member_id)
);
CREATE TABLE itinerary_items (
 id VARCHAR2(36 CHAR) PRIMARY KEY, trip_id VARCHAR2(36 CHAR) NOT NULL REFERENCES trips(id) ON DELETE CASCADE,
 day_index NUMBER(10) NOT NULL, sort_order NUMBER(10) NOT NULL, place_id VARCHAR2(100 CHAR) NOT NULL,
 place_name VARCHAR2(150 CHAR) NOT NULL, region VARCHAR2(50 CHAR) NOT NULL, category VARCHAR2(50 CHAR) NOT NULL,
 latitude BINARY_DOUBLE NOT NULL, longitude BINARY_DOUBLE NOT NULL,
 start_time VARCHAR2(5 CHAR) NOT NULL, duration NUMBER(10) NOT NULL, cost NUMBER(10) NOT NULL,
 indoor NUMBER(1) NOT NULL CHECK (indoor IN (0,1)), source VARCHAR2(30 CHAR) NOT NULL, place_url CLOB,
 fixed NUMBER(1) DEFAULT 0 NOT NULL CHECK (fixed IN (0,1)), booking_status VARCHAR2(30 CHAR) DEFAULT 'NONE' NOT NULL,
 booking_reason VARCHAR2(150 CHAR)
);
CREATE TABLE trip_history (
 id VARCHAR2(36 CHAR) PRIMARY KEY, trip_id VARCHAR2(36 CHAR) NOT NULL REFERENCES trips(id) ON DELETE CASCADE,
 member_id VARCHAR2(36 CHAR) NOT NULL REFERENCES members(id), version NUMBER(10) NOT NULL, summary VARCHAR2(200 CHAR) NOT NULL,
 snapshot CLOB NOT NULL, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);
CREATE TABLE invitations (
 id VARCHAR2(36 CHAR) PRIMARY KEY, trip_id VARCHAR2(36 CHAR) NOT NULL REFERENCES trips(id) ON DELETE CASCADE,
 sender_id VARCHAR2(36 CHAR) NOT NULL REFERENCES members(id), recipient_id VARCHAR2(36 CHAR) NOT NULL REFERENCES members(id),
 status VARCHAR2(20 CHAR) DEFAULT 'PENDING' NOT NULL, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);
CREATE TABLE trip_tasks (
 id VARCHAR2(36 CHAR) PRIMARY KEY, trip_id VARCHAR2(36 CHAR) NOT NULL REFERENCES trips(id) ON DELETE CASCADE,
 content VARCHAR2(200 CHAR) NOT NULL, done NUMBER(1) DEFAULT 0 NOT NULL CHECK (done IN (0,1))
);
CREATE TABLE expenses (
 id VARCHAR2(36 CHAR) PRIMARY KEY, trip_id VARCHAR2(36 CHAR) NOT NULL REFERENCES trips(id) ON DELETE CASCADE,
 member_id VARCHAR2(36 CHAR) NOT NULL REFERENCES members(id), label VARCHAR2(100 CHAR) NOT NULL, amount NUMBER(10) NOT NULL CHECK(amount > 0),
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);
CREATE TABLE posts (
 id VARCHAR2(36 CHAR) PRIMARY KEY, author_id VARCHAR2(36 CHAR) NOT NULL REFERENCES members(id), category VARCHAR2(30 CHAR) NOT NULL,
 region VARCHAR2(50 CHAR), title VARCHAR2(120 CHAR) NOT NULL, body CLOB,
 recruitment_date DATE, capacity NUMBER(10), status VARCHAR2(20 CHAR) DEFAULT 'OPEN' NOT NULL, hidden NUMBER(1) DEFAULT 0 NOT NULL CHECK (hidden IN (0,1)),
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);
CREATE TABLE comments (
 id VARCHAR2(36 CHAR) PRIMARY KEY, post_id VARCHAR2(36 CHAR) NOT NULL REFERENCES posts(id) ON DELETE CASCADE,
 author_id VARCHAR2(36 CHAR) NOT NULL REFERENCES members(id), body CLOB, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);
CREATE TABLE blocks (
 blocker_id VARCHAR2(36 CHAR) NOT NULL REFERENCES members(id), blocked_id VARCHAR2(36 CHAR) NOT NULL REFERENCES members(id),
 PRIMARY KEY(blocker_id,blocked_id)
);
CREATE TABLE conversations (
 id VARCHAR2(36 CHAR) PRIMARY KEY, requester_id VARCHAR2(36 CHAR) NOT NULL REFERENCES members(id), recipient_id VARCHAR2(36 CHAR) NOT NULL REFERENCES members(id),
 status VARCHAR2(20 CHAR) DEFAULT 'PENDING' NOT NULL, trip_id VARCHAR2(36 CHAR) REFERENCES trips(id) ON DELETE CASCADE,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);
CREATE TABLE messages (
 id VARCHAR2(36 CHAR) PRIMARY KEY, conversation_id VARCHAR2(36 CHAR) NOT NULL REFERENCES conversations(id) ON DELETE CASCADE,
 sender_id VARCHAR2(36 CHAR) NOT NULL REFERENCES members(id), body CLOB NOT NULL, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);
CREATE TABLE reports (
 id VARCHAR2(36 CHAR) PRIMARY KEY, reporter_id VARCHAR2(36 CHAR) NOT NULL REFERENCES members(id),
 target_type VARCHAR2(30 CHAR) NOT NULL, target_id VARCHAR2(36 CHAR) NOT NULL, reason VARCHAR2(1000 CHAR) NOT NULL,
 status VARCHAR2(20 CHAR) DEFAULT 'OPEN' NOT NULL, resolution VARCHAR2(1000 CHAR), created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);
CREATE TABLE admin_audit (
 id VARCHAR2(36 CHAR) PRIMARY KEY, admin_id VARCHAR2(36 CHAR) NOT NULL REFERENCES members(id), action VARCHAR2(200 CHAR) NOT NULL,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);
CREATE INDEX idx_items_trip ON itinerary_items(trip_id,day_index,sort_order);
CREATE INDEX idx_posts_created ON posts(created_at);
CREATE INDEX idx_messages_room ON messages(conversation_id,created_at);
