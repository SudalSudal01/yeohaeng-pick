-- 모든 도메인의 소유권은 외래키로 연결합니다. 예약·취향을 공개 게시물 JSON에 섞지 않습니다.
CREATE TABLE members (
 id VARCHAR(36) PRIMARY KEY, email VARCHAR(254) UNIQUE NOT NULL, password_hash VARCHAR(255) NOT NULL,
 nickname VARCHAR(40) NOT NULL, role VARCHAR(20) NOT NULL DEFAULT 'USER', verified BOOLEAN NOT NULL DEFAULT FALSE,
 preferences TEXT NOT NULL DEFAULT '[]', dm_scope VARCHAR(20) NOT NULL DEFAULT 'ALL',
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE email_tokens (
 token_hash VARCHAR(64) PRIMARY KEY, member_id VARCHAR(36) NOT NULL REFERENCES members(id),
 purpose VARCHAR(20) NOT NULL, expires_at TIMESTAMP NOT NULL
);
CREATE TABLE trips (
 id VARCHAR(36) PRIMARY KEY, owner_id VARCHAR(36) NOT NULL REFERENCES members(id), title VARCHAR(100) NOT NULL,
 regions TEXT NOT NULL, start_date DATE NOT NULL, end_date DATE NOT NULL, origin VARCHAR(150) NOT NULL,
 party_size INTEGER NOT NULL, budget INTEGER NOT NULL, transport VARCHAR(20) NOT NULL,
 preferences TEXT NOT NULL, lodging VARCHAR(150) NOT NULL DEFAULT '', version INTEGER NOT NULL DEFAULT 0,
 share_token VARCHAR(64) UNIQUE, created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE trip_members (
 trip_id VARCHAR(36) NOT NULL REFERENCES trips(id) ON DELETE CASCADE, member_id VARCHAR(36) NOT NULL REFERENCES members(id),
 PRIMARY KEY(trip_id, member_id)
);
CREATE TABLE itinerary_items (
 id VARCHAR(36) PRIMARY KEY, trip_id VARCHAR(36) NOT NULL REFERENCES trips(id) ON DELETE CASCADE,
 day_index INTEGER NOT NULL, sort_order INTEGER NOT NULL, place_id VARCHAR(100) NOT NULL,
 place_name VARCHAR(150) NOT NULL, region VARCHAR(50) NOT NULL, category VARCHAR(50) NOT NULL,
 latitude DOUBLE PRECISION NOT NULL, longitude DOUBLE PRECISION NOT NULL,
 start_time VARCHAR(5) NOT NULL, duration INTEGER NOT NULL, cost INTEGER NOT NULL,
 indoor BOOLEAN NOT NULL, source VARCHAR(30) NOT NULL, place_url TEXT NOT NULL DEFAULT '',
 fixed BOOLEAN NOT NULL DEFAULT FALSE, booking_status VARCHAR(30) NOT NULL DEFAULT 'NONE',
 booking_reason VARCHAR(150) NOT NULL DEFAULT ''
);
CREATE TABLE trip_history (
 id VARCHAR(36) PRIMARY KEY, trip_id VARCHAR(36) NOT NULL REFERENCES trips(id) ON DELETE CASCADE,
 member_id VARCHAR(36) NOT NULL REFERENCES members(id), version INTEGER NOT NULL, summary VARCHAR(200) NOT NULL,
 snapshot TEXT NOT NULL, created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE invitations (
 id VARCHAR(36) PRIMARY KEY, trip_id VARCHAR(36) NOT NULL REFERENCES trips(id) ON DELETE CASCADE,
 sender_id VARCHAR(36) NOT NULL REFERENCES members(id), recipient_id VARCHAR(36) NOT NULL REFERENCES members(id),
 status VARCHAR(20) NOT NULL DEFAULT 'PENDING', created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE trip_tasks (
 id VARCHAR(36) PRIMARY KEY, trip_id VARCHAR(36) NOT NULL REFERENCES trips(id) ON DELETE CASCADE,
 content VARCHAR(200) NOT NULL, done BOOLEAN NOT NULL DEFAULT FALSE
);
CREATE TABLE expenses (
 id VARCHAR(36) PRIMARY KEY, trip_id VARCHAR(36) NOT NULL REFERENCES trips(id) ON DELETE CASCADE,
 member_id VARCHAR(36) NOT NULL REFERENCES members(id), label VARCHAR(100) NOT NULL, amount INTEGER NOT NULL CHECK(amount > 0),
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE posts (
 id VARCHAR(36) PRIMARY KEY, author_id VARCHAR(36) NOT NULL REFERENCES members(id), category VARCHAR(30) NOT NULL,
 region VARCHAR(50) NOT NULL, title VARCHAR(120) NOT NULL, body TEXT NOT NULL,
 recruitment_date DATE, capacity INTEGER, status VARCHAR(20) NOT NULL DEFAULT 'OPEN', hidden BOOLEAN NOT NULL DEFAULT FALSE,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE comments (
 id VARCHAR(36) PRIMARY KEY, post_id VARCHAR(36) NOT NULL REFERENCES posts(id) ON DELETE CASCADE,
 author_id VARCHAR(36) NOT NULL REFERENCES members(id), body VARCHAR(2000) NOT NULL, created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE blocks (
 blocker_id VARCHAR(36) NOT NULL REFERENCES members(id), blocked_id VARCHAR(36) NOT NULL REFERENCES members(id),
 PRIMARY KEY(blocker_id,blocked_id)
);
CREATE TABLE conversations (
 id VARCHAR(36) PRIMARY KEY, requester_id VARCHAR(36) NOT NULL REFERENCES members(id), recipient_id VARCHAR(36) NOT NULL REFERENCES members(id),
 status VARCHAR(20) NOT NULL DEFAULT 'PENDING', trip_id VARCHAR(36) REFERENCES trips(id) ON DELETE CASCADE,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE messages (
 id VARCHAR(36) PRIMARY KEY, conversation_id VARCHAR(36) NOT NULL REFERENCES conversations(id) ON DELETE CASCADE,
 sender_id VARCHAR(36) NOT NULL REFERENCES members(id), body VARCHAR(2000) NOT NULL, created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE reports (
 id VARCHAR(36) PRIMARY KEY, reporter_id VARCHAR(36) NOT NULL REFERENCES members(id),
 target_type VARCHAR(30) NOT NULL, target_id VARCHAR(36) NOT NULL, reason VARCHAR(1000) NOT NULL,
 status VARCHAR(20) NOT NULL DEFAULT 'OPEN', resolution VARCHAR(1000) NOT NULL DEFAULT '', created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE admin_audit (
 id VARCHAR(36) PRIMARY KEY, admin_id VARCHAR(36) NOT NULL REFERENCES members(id), action VARCHAR(200) NOT NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_items_trip ON itinerary_items(trip_id,day_index,sort_order);
CREATE INDEX idx_posts_created ON posts(created_at);
CREATE INDEX idx_messages_room ON messages(conversation_id,created_at);
